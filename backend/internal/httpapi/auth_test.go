func TestLoginNonceConsumedAtomically(t *testing.T) {
	f := newAuthFixture(t)
	client := f.client(t)
	envelope, _ := f.request(t, client, "GET", "/auth/login-challenge", nil, "", 200)
	nonce := authData(t, envelope)["loginNonce"].(string)
	results := make(chan int, 2)
	for i := 0; i < 2; i++ {
		go func() {
			body, _ := json.Marshal(map[string]string{"username": "xiaowork", "password": authTestPassword})
			req, _ := http.NewRequest("POST", f.server.URL+apiPrefix+"/auth/login", bytes.NewReader(body))
			req.Header.Set("Origin", f.server.URL)
			req.Header.Set("X-CSRF-Token", nonce)
			req.Header.Set("Content-Type", "application/json")
			response, err := client.Do(req)
			if err != nil {
				results <- 0
				return
			}
			io.Copy(io.Discard, response.Body)
			response.Body.Close()
			results <- response.StatusCode
		}()
	}
	first, second := <-results, <-results
	if !((first == 200 && second == 403) || (first == 403 && second == 200)) {
		t.Fatalf("concurrent nonce use expected=one200+one403 actual=%d+%d", first, second)
	}
	t.Logf("HTTP POST /auth/login simultaneous same nonce expected=200+403 actual=%d+%d", first, second)
}

