func TestAbsoluteSessionExpiryDespiteContinuousHTTPSActivity(t *testing.T) {
	f := newAuthFixture(t)
	client := f.client(t)
	start := f.clock.Load()
	f.loginAs(t, client, "xiaowork", authTestPassword, 200)
	// Each successful authenticated workspace read renews idle activity. Twenty
	// minutes is below the thirty-minute idle limit, so idle expiry cannot explain
	// the final rejection at the independent twelve-hour absolute boundary.
	for elapsed := int64(1200); elapsed < 43200; elapsed += 1200 {
		f.clock.Store(start + elapsed)
		f.request(t, client, "GET", "/workspace", nil, "", 200)
	}
	f.clock.Store(start + 43199)
	f.request(t, client, "GET", "/workspace", nil, "", 200)
	var lastInteractive, absoluteExpiry int64
	if err := f.db.QueryRow("SELECT last_interactive_at,expires_at FROM sessions WHERE revoked_at IS NULL").Scan(&lastInteractive, &absoluteExpiry); err != nil {
		t.Fatal(err)
	}
	if lastInteractive != start+43199 || absoluteExpiry != start+43200 {
		t.Fatal("successful activity failed to refresh idle or changed the absolute deadline")
	}
	f.clock.Store(start + 43200)
	f.request(t, client, "GET", "/auth/session", nil, "", 401)
	t.Log("HTTPS absolute-expiry isolation: last successful interaction one second before unchanged 12h deadline; exact deadline rejected with 401")
}
