func TestProxyHeadersCannotSpoofHTTPSOrSource(t *testing.T) {
	a := &App{config: Config{TrustedProxyCIDRs: []netip.Prefix{netip.MustParsePrefix("10.9.0.0/24")}}}
	req := httptest.NewRequest("POST", "http://example.test/api/admin/v1/auth/login", nil)
	req.RemoteAddr = "203.0.113.9:4444"
	req.Header.Set("X-Forwarded-Proto", "https")
	req.Header.Set("X-Forwarded-For", "198.51.100.8")
	if a.secureRequest(req) || a.sourceAddress(req) != "203.0.113.9" {
		t.Fatal("untrusted peer forwarding headers were accepted")
	}
	req.RemoteAddr = "10.9.0.2:4444"
	if !a.secureRequest(req) || a.sourceAddress(req) != "198.51.100.8" {
		t.Fatal("trusted proxy was not recognized")
	}
	req.Header.Set("X-Forwarded-Proto", "https,http")
	if a.secureRequest(req) {
		t.Fatal("ambiguous forwarding protocol accepted")
	}
}

func TestAuthenticationCapacityLimits(t *testing.T) {
	a := &App{authSlots: make(chan struct{}, 2), authQueue: make(chan struct{}, 4)}
	for i := 0; i < 2; i++ {
		a.authSlots <- struct{}{}
	}
	for i := 0; i < 4; i++ {
		a.authQueue <- struct{}{}
	}
	if release, err := a.acquireAuth(context.Background()); err == nil {
		release()
		t.Fatal("full hash queue accepted more work")
	}
	<-a.authQueue
	started := time.Now()
	if release, err := a.acquireAuth(context.Background()); err == nil {
		release()
		t.Fatal("hash wait did not time out")
	}
	if time.Since(started) < 1900*time.Millisecond || time.Since(started) > 3*time.Second {
		t.Fatal("hash queue timeout does not match 2 seconds")
	}
	<-a.authSlots
	release, err := a.acquireAuth(context.Background())
	if err != nil {
		t.Fatal("released hash slot unavailable", err)
	}
	release()
}

