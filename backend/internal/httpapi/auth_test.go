const authTestPassword = "Test-only secure password 2026"

type authFixture struct {
	db     *sql.DB
	app    *App
	server *httptest.Server
	clock  atomic.Int64
}

func newAuthFixture(t *testing.T) *authFixture {
	t.Helper()
	f := &authFixture{}
	var err error
	f.db, err = store.Open(filepath.Join(t.TempDir(), "auth.sqlite"), true)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { f.db.Close() })
	if err = store.Migrate(context.Background(), f.db); err != nil {
		t.Fatal(err)
	}
	if err = authn.InitAdministrator(context.Background(), f.db, "xiaowork", []byte(authTestPassword)); err != nil {
		t.Fatal(err)
	}
	// CLI initialization uses real time after Argon2 finishes. Freeze the API
	// clock afterwards so it cannot predate administrators.created_at when
	// initialization crosses a second boundary under CPU load.
	f.clock.Store(time.Now().UTC().Unix())
	f.server = httptest.NewUnstartedServer(http.NotFoundHandler())
	origin := "https://" + f.server.Listener.Addr().String()
	// TempDir's leaf can inherit a permissive umask on Unix. Model the private
	// runtime upload volume explicitly rather than weakening mediaRoot's checks.
	uploadDir := filepath.Join(t.TempDir(), "uploads")
	if err = os.Mkdir(uploadDir, 0700); err != nil {
		t.Fatal(err)
	}
	f.app, err = New(f.db, Config{Origin: origin, Secret: bytes.Repeat([]byte{0x42}, 32), UploadDir: uploadDir, Clock: func() time.Time { return time.Unix(f.clock.Load(), 0).UTC() }})
	if err != nil {
		t.Fatal(err)
	}
	f.server.Config.Handler = f.app.Handler()
	f.server.StartTLS()
	transport, ok := f.server.Client().Transport.(*http.Transport)
	if !ok || transport.TLSClientConfig == nil || transport.TLSClientConfig.InsecureSkipVerify || transport.TLSClientConfig.RootCAs == nil {
		t.Fatal("HTTPS integration requires an explicit trusted test certificate with verification enabled")
	}
	t.Cleanup(f.server.Close)
	return f
}

func (f *authFixture) client(t *testing.T) *http.Client {
	t.Helper()
	jar, err := cookiejar.New(nil)
	if err != nil {
		t.Fatal(err)
	}
	// The transport trusts the exact certificate generated by httptest. It does
	// not disable TLS verification and it is never used outside this test server.
	return &http.Client{Transport: f.server.Client().Transport, Jar: jar, Timeout: 10 * time.Second}
}

func (f *authFixture) request(t *testing.T, client *http.Client, method, path string, body any, csrf string, expected int) (map[string]any, *http.Response) {
	t.Helper()
	var reader io.Reader
	if body != nil {
		encoded, err := json.Marshal(body)
		if err != nil {
			t.Fatal(err)
		}
		reader = bytes.NewReader(encoded)
	}
	req, err := http.NewRequest(method, f.server.URL+apiPrefix+path, reader)
	if err != nil {
		t.Fatal(err)
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	if method != "GET" && method != "HEAD" {
		req.Header.Set("Origin", f.server.URL)
	}
	if csrf != "" {
		req.Header.Set("X-CSRF-Token", csrf)
	}
	res, err := client.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer res.Body.Close()
	data, err := io.ReadAll(res.Body)
	if err != nil {
		t.Fatal(err)
	}
	if res.StatusCode != expected {
		t.Fatalf("%s %s expected=%d actual=%d body=%s", method, path, expected, res.StatusCode, data)
	}
	if res.Header.Get("Cache-Control") != "no-store" || !strings.Contains(res.Header.Get("X-Robots-Tag"), "noindex") {
		t.Fatal("sensitive response lacks no-store/noindex")
	}
	t.Logf("HTTP %s %s expected=%d actual=%d", method, path, expected, res.StatusCode)
	result := map[string]any{}
	if len(data) > 0 {
		if err = json.Unmarshal(data, &result); err != nil {
			t.Fatalf("response is not JSON: %s", data)
		}
	}
	return result, res
}

func authData(t *testing.T, envelope map[string]any) map[string]any {
	t.Helper()
	data, ok := envelope["data"].(map[string]any)
	if !ok {
		t.Fatalf("missing data: %#v", envelope)
	}
	return data
}

func (f *authFixture) loginAs(t *testing.T, client *http.Client, username, password string, expected int) (string, *http.Response) {
	t.Helper()
	challenge, _ := f.request(t, client, "GET", "/auth/login-challenge", nil, "", 200)
	nonce := authData(t, challenge)["loginNonce"].(string)
	result, res := f.request(t, client, "POST", "/auth/login", map[string]string{"username": username, "password": password}, nonce, expected)
	if expected != 200 {
		return "", res
	}
	return authData(t, result)["csrfToken"].(string), res
}

func TestAuthenticationHTTPSLifecycleAndCSRF(t *testing.T) {
	f := newAuthFixture(t)
	client := f.client(t)
	f.request(t, client, "GET", "/workspace", nil, "", 401)
	csrf, res := f.loginAs(t, client, "xiaowork", authTestPassword, 200)
	found := false
	for _, cookie := range res.Cookies() {
		if cookie.Name == sessionCookieName {
			found = true
			if !cookie.Secure || !cookie.HttpOnly || cookie.SameSite != http.SameSiteStrictMode || cookie.Path != "/" || cookie.Domain != "" || cookie.MaxAge > 43200 {
				t.Fatalf("unsafe session cookie: %#v", cookie)
			}
		}
	}
	if !found {
		t.Fatal("session cookie missing")
	}
	first, _ := f.request(t, client, "GET", "/auth/session", nil, "", 200)
	second, _ := f.request(t, client, "GET", "/auth/session", nil, "", 200)
	if authData(t, first)["csrfToken"] != csrf || authData(t, second)["csrfToken"] != csrf {
		t.Fatal("CSRF token changed across reads")
	}
	f.request(t, client, "POST", "/auth/logout", map[string]any{}, "", 403)
	f.request(t, client, "POST", "/auth/logout", map[string]any{}, strings.Repeat("a", 43), 403)
	req, _ := http.NewRequest("POST", f.server.URL+apiPrefix+"/auth/logout", strings.NewReader("{}"))
	req.Header.Set("Origin", "https://attacker.invalid")
	req.Header.Set("X-CSRF-Token", csrf)
	req.Header.Set("Content-Type", "application/json")
	bad, err := client.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	bad.Body.Close()
	if bad.StatusCode != 403 {
		t.Fatal("cross-origin mutation accepted")
	}
	t.Log("HTTP POST /auth/logout foreign Origin expected=403 actual=403")
	f.request(t, client, "POST", "/auth/logout", nil, csrf, 204)
	f.request(t, client, "GET", "/auth/session", nil, "", 401)
	var storedHash string
	if err = f.db.QueryRow("SELECT token_hash FROM sessions LIMIT 1").Scan(&storedHash); err != nil || len(storedHash) != 64 {
		t.Fatal("session not persisted as a hash", err)
	}
}

